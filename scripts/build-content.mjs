/* Builds supabase/functions/_shared/content.js from the files in content/.
   The content files share one scope (like several <script> tags on one page), so they are joined in order
   into one ES module that both the Supabase Edge Function (Deno) and the Node tests can import.
   Run after any change to content/:   npm run build        (npm test runs it too) */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ORDER = ['lib.js', 'figs.js', 'l2.js', 'e1.js', 'e2.js', 'e3.js', 'l1.js', 'tail.js'];
let out = '/* GENERATED by scripts/build-content.mjs from content/*.js. Do not edit by hand. */\n';
for (const f of ORDER) {
  let src = readFileSync(join(root, 'content', f), 'utf8').replace(/^\s*["']use strict["'];?\s*/, '');
  if (f === 'tail.js') {
    // the last expression of tail.js is the object handed to the server
    const i = src.lastIndexOf('({');
    if (i < 0) throw new Error('tail.js: could not find the exported object');
    src = src.slice(0, i) + 'export default ' + src.slice(i + 1).replace(/\}\);?\s*$/, '};\n');
  }
  out += `\n/* ===== content/${f} ===== */\n` + src;
}
const target = join(root, 'supabase', 'functions', '_shared', 'content.js');
writeFileSync(target, out);
console.log('Wrote', target, Math.round(out.length / 1024) + ' KB');
