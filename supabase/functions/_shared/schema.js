/* The database layout. Everything lives in its own Postgres schema, "gf", which Supabase does NOT expose
   through its public REST API: only the Edge Function (which holds the database connection) can read it.
   Each entry in MIGRATIONS runs once, in order. To change the database later, ADD a new entry at the end;
   never edit one that has already run. The number reached is stored in gf.meta (key 'schema_version'). */
export const MIGRATIONS = [
  /* 1: first version */
  `CREATE TABLE IF NOT EXISTS users(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,username text UNIQUE NOT NULL,name text NOT NULL,role text NOT NULL,pass text NOT NULL,
     level text,grp text DEFAULT '',block integer DEFAULT 1,active integer DEFAULT 1,extra_time integer DEFAULT 0,created bigint,last_seen bigint);
   CREATE TABLE IF NOT EXISTS sessions(token text PRIMARY KEY,user_id integer NOT NULL,expires bigint NOT NULL,last_active bigint NOT NULL);
   CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
   CREATE TABLE IF NOT EXISTS progress(user_id integer,topic text,attempts integer DEFAULT 0,correct integer DEFAULT 0,recent text DEFAULT '',lesson integer DEFAULT 0,diag integer,updated bigint,PRIMARY KEY(user_id,topic));
   CREATE TABLE IF NOT EXISTS answers(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id integer,topic text,ok integer,src text,quiz_id integer,given text,ts bigint);
   CREATE INDEX IF NOT EXISTS answers_user ON answers(user_id,ts);
   CREATE INDEX IF NOT EXISTS answers_quiz ON answers(quiz_id);
   CREATE TABLE IF NOT EXISTS open_q(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id integer,topic text,mode text,seed integer,gen integer,tries integer DEFAULT 0,done integer DEFAULT 0,ts bigint);
   CREATE INDEX IF NOT EXISTS open_q_user ON open_q(user_id,id);
   CREATE TABLE IF NOT EXISTS assigned(user_id integer,topic text,ts bigint,PRIMARY KEY(user_id,topic));
   CREATE TABLE IF NOT EXISTS quizzes(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,title text,level text,kind text,spec text,params text,minutes integer,created bigint,created_by integer);
   CREATE TABLE IF NOT EXISTS quiz_users(quiz_id integer,user_id integer,spec text,PRIMARY KEY(quiz_id,user_id));
   CREATE TABLE IF NOT EXISTS attempts(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,quiz_id integer,user_id integer,started bigint,ends_at bigint,finished bigint,answers text,score integer,total integer,detail text,UNIQUE(quiz_id,user_id));
   CREATE TABLE IF NOT EXISTS notes(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id integer,topic text,context text DEFAULT '',text text,image text,ts bigint);
   CREATE TABLE IF NOT EXISTS settings(key text PRIMARY KEY,value text);
   CREATE TABLE IF NOT EXISTS videos(topic text PRIMARY KEY,url text);
   CREATE TABLE IF NOT EXISTS login_fails(key text PRIMARY KEY,n integer,last bigint,until bigint);
   CREATE TABLE IF NOT EXISTS audit(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ts bigint,user_id integer,who text,action text,detail text);
   CREATE INDEX IF NOT EXISTS audit_ts ON audit(ts);`,
];

/* Day of a timestamp (milliseconds) in UK time, as YYYY-MM-DD. Used for "days of practice" and the activity chart. */
export const DAY_FN = `CREATE OR REPLACE FUNCTION gf.gf_day(ms bigint) RETURNS text LANGUAGE sql IMMUTABLE AS
  $$ SELECT to_char(to_timestamp(ms/1000.0) AT TIME ZONE 'Europe/London','YYYY-MM-DD') $$;`;

/* Belt and braces: the Supabase "anon" and "authenticated" roles get no access to the gf schema.
   Wrapped so it also runs on plain Postgres where those roles do not exist. */
export const LOCKDOWN = `DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN EXECUTE 'REVOKE ALL ON SCHEMA gf FROM anon'; EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA gf FROM anon'; END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN EXECUTE 'REVOKE ALL ON SCHEMA gf FROM authenticated'; EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA gf FROM authenticated'; END IF;
END $$;`;

export async function ensureSchema(db) {
  await db.exec('CREATE SCHEMA IF NOT EXISTS gf; SET search_path TO gf;CREATE TABLE IF NOT EXISTS gf.meta(key text PRIMARY KEY,value text);');
  const r = await db.query("SELECT value FROM gf.meta WHERE key='schema_version'");
  let v = r.length ? +r[0].value : 0;
  while (v < MIGRATIONS.length) {
    await db.exec('SET search_path TO gf;' + MIGRATIONS[v]);
    v++;
    await db.query("INSERT INTO gf.meta(key,value) VALUES('schema_version',$1) ON CONFLICT(key) DO UPDATE SET value=excluded.value", [String(v)]);
  }
  await db.exec(DAY_FN);
  await db.exec(LOCKDOWN);
  return v;
}
